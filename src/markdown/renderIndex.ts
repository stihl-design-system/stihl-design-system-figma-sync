import { posix } from 'node:path';
import type { DocCategory } from '../config.ts';
import type { Frontmatter } from './renderMarkdown.ts';

export interface DocumentHeading {
  level: number;
  /** Heading text as written in the Markdown (escapes included) */
  text: string;
}

export interface IndexEntry {
  frontmatter: Frontmatter;
  /** Path of the Markdown file, relative to the repository root */
  path: string;
  headings: DocumentHeading[];
}

const CATEGORY_TITLES: Record<DocCategory, string> = {
  component: 'Components',
  pattern: 'Patterns',
  foundation: 'Foundations',
};

const INTRO = `# STIHL Design System: design documentation from Figma

> Generated by \`npm run sync\` from the documentation pages in the STIHL Design System Figma files. Do not edit these files; the next sync overwrites them.

## How to use these files

- One Markdown file per document, grouped by category (\`components/\`, \`patterns/\`, \`foundations/\`). Exported images live in a folder of the same name next to the file.
- \`#\` is the document title. \`##\` chapters follow the boards the designers laid out in Figma; \`###\` and \`####\` are their sections. Heading levels never skip, so a chapter can be fetched on its own by heading when the whole file is too long.
- The frontmatter carries the Figma source (\`sourceUrl\`, \`figmaVersion\`, \`figmaVersionLabel\`) and, where a code component exists, \`importName\` and \`package\` to look it up in Storybook, plus \`keywords\` for search.
- The documents cover design guidance: anatomy, sizing, content rules, do's and don'ts, behavior, use cases. Props, types and code examples are not in here; query the Storybook MCP server or \`llms-full.txt\` of the component library for those.
- Images are referenced relatively and have the section title as alt text, so the text stays meaningful without rendering them.
`;

/** GitHub style heading anchor */
export function headingSlug(text: string): string {
  return text
    .replace(/\\([\\`*_[\]<>])/g, '$1')
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s-]/gu, '')
    .trim()
    .replace(/\s+/g, '-');
}

export function parseHeadings(markdown: string): DocumentHeading[] {
  const body = markdown.replace(/^---\n[\s\S]*?\n---\n/, '');
  const headings: DocumentHeading[] = [];
  for (const line of body.split('\n')) {
    const match = line.match(/^(#{1,6}) (.+)$/);
    if (match?.[1] && match[2]) {
      headings.push({ level: match[1].length, text: match[2] });
    }
  }
  return headings;
}

function withUniqueSlugs(
  headings: DocumentHeading[]
): (DocumentHeading & { slug: string })[] {
  const seen = new Map<string, number>();
  return headings.map((heading) => {
    const base = headingSlug(heading.text);
    const count = seen.get(base) ?? 0;
    seen.set(base, count + 1);
    return { ...heading, slug: count === 0 ? base : `${base}-${count}` };
  });
}

function renderEntry(entry: IndexEntry, indexPath: string): string {
  const { frontmatter } = entry;
  const href = posix.relative(posix.dirname(indexPath), entry.path);
  const lines = [`### ${frontmatter.title}`, ''];

  const summary: string[] = [];
  if (frontmatter.importName) {
    summary.push(
      `\`${frontmatter.importName}\`${frontmatter.package ? ` from \`${frontmatter.package}\`` : ''}.`
    );
  }
  if (frontmatter.keywords?.length) {
    summary.push(`Keywords: ${frontmatter.keywords.join(', ')}.`);
  }
  if (summary.length > 0) {
    lines.push(summary.join(' '), '');
  }

  lines.push(`- Document: [${href}](${href})`);
  const versionDate = frontmatter.figmaVersionCreatedAt.slice(0, 10);
  const versionLabel = frontmatter.figmaVersionLabel
    ? `version "${frontmatter.figmaVersionLabel}", ${versionDate}`
    : `unpublished state, ${versionDate}`;
  lines.push(
    `- Figma: [${frontmatter.title}](${frontmatter.sourceUrl}) (${versionLabel})`
  );

  // H4 and below are section titles; H2/H3 are enough to pick a chapter
  const chapters = withUniqueSlugs(entry.headings).filter(
    (heading) => heading.level === 2 || heading.level === 3
  );
  if (chapters.length > 0) {
    lines.push('- Chapters:');
    for (const chapter of chapters) {
      const indent = chapter.level === 2 ? '  ' : '    ';
      lines.push(`${indent}- [${chapter.text}](${href}#${chapter.slug})`);
    }
  }
  return lines.join('\n');
}

export function renderIndex(entries: IndexEntry[], indexPath: string): string {
  const sections: string[] = [INTRO.trimEnd()];
  for (const category of Object.keys(CATEGORY_TITLES) as DocCategory[]) {
    const inCategory = entries
      .filter((entry) => entry.frontmatter.category === category)
      .sort((a, b) => a.frontmatter.title.localeCompare(b.frontmatter.title));
    if (inCategory.length === 0) {
      continue;
    }
    sections.push(`## ${CATEGORY_TITLES[category]}`);
    for (const entry of inCategory) {
      sections.push(renderEntry(entry, indexPath));
    }
  }
  return `${sections.join('\n\n')}\n`;
}
